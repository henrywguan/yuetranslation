export type HarborRpgMountDef = {
  id: HarborRpgMountId
  name: { en: string; zh: string }
  /** Public URL under Vite. */
  src: string
  pack: 'quaternius' | 'farm' | 'gobkit'
  /** Uniform scale after load. */
  scale: number
  /** Walk speed multiplier vs HARBOR_WALK_SPEED. */
  speedMult: number
  /** Rider sit height above mount root (world units). */
  saddleY: number
  /** Prefer these clip name substrings (case-insensitive). */
  clips: { idle: string[]; walk: string[]; gallop: string[] }
  /** Gold cost at Town stable (0 = starter unlock). */
  cost: number
  /** Soft unlock hint. */
  blurb: { en: string; zh: string }
}


export function isHarborRpgMountId(raw: unknown): raw is HarborRpgMountId {
  return typeof raw === 'string' && (HARBOR_RPG_MOUNT_IDS as readonly string[]).includes(raw)
}

export function harborRpgMountById(id: string): HarborRpgMountDef | null {
  return isHarborRpgMountId(id) ? HARBOR_RPG_MOUNT_DEFS[id] : null
}

